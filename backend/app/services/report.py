    def generate_openapi_spec(self, repo_id: int) -> Dict[str, Any]:
        """
        Dynamically constructs an OpenAPI 3.0.0 specification dictionary
        based on AST discovered endpoints stored in the database.
        """
        repo = self.db.query(Repository).filter(Repository.id == repo_id).first()
        if not repo:
            return {}
        endpoints = self.db.query(APIEndpoint).filter(APIEndpoint.repository_id == repo_id).all()
        spec = {
            "openapi": "3.0.0",
            "info": {
                "title": f"{repo.name} API Spec",
                "description": f"Auto-generated by AutoDoc AI Engine for the {repo.framework or 'python'} repository.",
                "version": "1.0.0"
            },
            "paths": {}
        }
        for ep in endpoints:
            # OpenAPI paths require leading slash
            route = ep.route
            if not route.startswith("/"):
                route = "/" + route
            # Replace any double slashes
            route = route.replace("//", "/")
            if route not in spec["paths"]:
                spec["paths"][route] = {}
            method = ep.method.lower()
            
            # Format parameters
            parameters = []
            if ep.parameters:
                for param in ep.parameters:
                    # In DB, param is a dictionary: {name, type, required, default, location}
                    p_name = param.get("name", "")
                    p_location = param.get("location", "query")
                    # Map locations to OpenAPI specs (query, path, header, cookie)
                    if p_location not in ["query", "path", "header", "cookie"]:
                        p_location = "query"
                    parameters.append({
                        "name": p_name,
                        "in": p_location,
                        "required": param.get("required", True),
                        "schema": {
                            "type": param.get("type") or "string"
                        },
                        "description": f"Default: {param.get('default')}" if param.get("default") else ""
                    })
            # Check authentication to apply security schemas
            security = []
            if ep.auth:
                security.append({"OAuth2Bearer": []})
                if "components" not in spec:
                    spec["components"] = {
                        "securitySchemes": {
                            "OAuth2Bearer": {
                                "type": "http",
                                "scheme": "bearer",
                                "bearerFormat": "JWT"
                            }
                        }
                    }
            spec["paths"][route][method] = {
                "summary": ep.function_name.replace("_", " ").title(),
                "description": ep.docstring or f"Handler: {ep.function_name}",
                "parameters": parameters,
                "responses": {
                    str(ep.status_code or 200): {
                        "description": "Successful Response"
                    }
                }
            }
            if security:
                spec["paths"][route][method]["security"] = security
            if ep.tags:
                spec["paths"][route][method]["tags"] = ep.tags
        return spec
